# Пары чисел. Дан список чисел - найти все пары элементов, сумма которых равна 10

a = [5, 17, 7, 3, -7]
for i in range(len(a) - 1):
    if a[i] + a[i + 1] == 10:
        print(a[i], a[i + 1])

# i -> range(0,4)
#
# i = 0 (a[0], a[1])
# i = 1 (a[1], a[2])
# i = 2 (a[2], a[3])
